// React --> React is a frontend javascript library used for building user interface specially for single page application. it uses component based approach and virtual DOM which makes it faster.


// Component --> component is a small reusable piece of code or a part of UI. components are two type class based component and functional components.

// functional component --> similar like functions in javascript but functional component returns a react element(Tag). component is consist of html css js code

// Hooks --> hooks are functions. with the help of hooks you can define state in your react application. example --> useState hook, useReducer , useEffect , useContext etc.

// State --> are used to store the value that can be changed over a period of time

// Virtual DOM --> it is a copy of actual DOM (memory representation of actual DOM). whenever any components state or props changes it creates a new Virtual DOM tree and then compare it to the previous tree and then apply minimum set to changes require in actual DOM.

//props --> with the help of props you can pass data from parent component to child component


// Conditional Rendering --> using && operator  and using ternary operator

// React routings --> using react-router-dom(BrowserRouter, Routes, Route, Link)

// useState Hook --> used to store value and can be used to re-render of component. it take a array of two arguments a variable and a function. with the help of function we can update or replace the value of variable. whenever the update function will run react re-renders the whole component
// example-->  const [data , setData ] = useState(10);

// useEffect Hook --> useEffect hook is used to run side effect such as updating the Dom  element , fething Api etc. it takes two arguments , a callback function and a array of dependency. if array of dependency is blank useEffect will run only one time. useEffect always run after the first render of component

